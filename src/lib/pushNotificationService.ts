/**
 * Check upcoming turnos scheduled for tomorrow and dispatch reminders automatically
 */
export async function verificarYEnviarRecordatorios24h(
  turnosOrNegocioId?: Turno[] | string,
  configParam?: BusinessConfig
): Promise<number> {
  const now = new Date();
  const tomorrow = new Date(now);
  tomorrow.setDate(tomorrow.getDate() + 1);
  const tomorrowStr = tomorrow.toISOString().split('T')[0];

  let turnos: Turno[] = [];
  const config: BusinessConfig = configParam || {
    ...DEFAULT_CONFIG,
    id: typeof turnosOrNegocioId === 'string' ? turnosOrNegocioId : 'perfect-glass',
  };

  if (Array.isArray(turnosOrNegocioId)) {
    turnos = turnosOrNegocioId;
  } else {
    try {
      const q = query(
        collection(db, 'turnos'),
        where('fecha', '==', tomorrowStr),
        where('estado', '==', 'confirmado')
      );
      const snap = await getDocs(q);
      turnos = snap.docs.map((d) => ({ id: d.id, ...d.data() } as Turno));
    } catch (e) {
      console.warn('Error querying upcoming turnos for 24h reminders:', e);
      return 0;
    }
  }

  if (turnos.length === 0) return 0;

  let enviados = 0;
  for (const t of turnos) {
    if (
      t.estado === 'confirmado' &&
      t.fecha === tomorrowStr &&
      !t.recordatorioEnviado
    ) {
      try {
        await enviarNotificacionRecordatorioCliente(t, config);
        enviados++;
      } catch (e) {
        console.warn('Error sending 24h reminder for turno:', t.id, e);
      }
    }
  }

  return enviados;
}
